// Concatenate src/*.js into lib/client.js, the file DSH's client module loader
// evaluates: `npm run build`. Zero dependencies, no transforms — the sources
// share one factory scope, in the order below.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ORDER = ['constants', 'prefs', 'art', 'markup', 'style', 'overlay', 'actions', 'settings', 'plugin']
const root = fileURLToPath(new URL('..', import.meta.url))

/** @returns the generated lib/client.js text. */
export function build() {
  const parts = ORDER.map((name) => {
    const text = readFileSync(`${root}src/${name}.js`, 'utf8').trimEnd()
    return `//#region src/${name}.js\n${text}\n//#endregion`
  })
  return `window.__ModuleLoader__.load({
  id: 'dsh-gov-boot',
  factory: (require) => {
var module = { exports: {} }
var exports = module.exports
// Generated by scripts/build.mjs from src/. Edit those files, then run \`npm run build\`.

${parts.join('\n\n')}

return module.exports
  },
})
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(`${root}lib/client.js`, build())
  console.log('lib/client.js written from ' + ORDER.length + ' sources')
}
